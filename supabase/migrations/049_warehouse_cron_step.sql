-- Migration 049: автосинк складу без ризику таймауту на serverless-хостингу
--
-- Проблема, яку тут вирішуємо: /api/cron/warehouse-sync якав ВСІ прайси
-- бізнесу і одразу зводив їх зі складом в ОДНОМУ виклику функції. На
-- Netlify (і на більшості serverless-хостингів) функція обривається
-- через 10–26 секунд незалежно від `maxDuration` у коді — це
-- налаштування розуміє тільки Vercel. Кілька великих прайсів + тисячі
-- товарів складу в одному виклику стабільно впирались у цей ліміт.
--
-- Рішення — той самий принцип, що вже застосований до ручних кнопок:
-- розрізати роботу на дрібні кроки. Але автосинк не має браузера, який
-- по черзі натискає кнопки, тому крок «просуває» сам себе: зовнішній
-- плановик (cron-job.org) стукає в ендпоінт часто (раз на кілька
-- хвилин), а сам ендпоінт щоразу робить РІВНО ОДНУ дію — качає один
-- прострочений прайс або, якщо всі прайси вже свіжі, зводить склад —
-- і виходить. За кілька тіків усе встигає оновитись, і жоден окремий
-- виклик не наближається до ліміту хостингу.
--
-- Щоб ендпоінт знав, чи вже зводив склад після останньої підкачки,
-- потрібна одна нова відмітка часу.

alter table public.warehouse_settings
  add column if not exists last_matched_at timestamptz;

comment on column public.warehouse_settings.last_matched_at is
  'Коли востаннє відбувалась звірка складу з кешем прайсів (крок 2 автосинку). '
  'Порівнюється з max(supplier_feeds.last_synced_at): якщо підкачка новіша '
  'за останню звірку — автосинк знає, що звірку треба повторити.';
